#!/usr/bin/env python3
"""Embed files into a C source as a name -> bytes table.

usage: embed.py OUT.c NAME=PATH [NAME=PATH ...]
"""
import sys


def main():
    out, pairs = sys.argv[1], sys.argv[2:]
    lines = ['/* generated by tools/embed.py - do not edit */',
             '#include "core/assets.h"', '']
    table = []
    for i, pair in enumerate(pairs):
        name, path = pair.split('=', 1)
        data = open(path, 'rb').read()
        lines.append(f'static const unsigned char a{i}[{len(data) + 1}] __attribute__((aligned(16))) = {{')
        for off in range(0, len(data), 24):
            lines.append('  ' + ','.join(str(b) for b in data[off:off + 24]) + ',')
        lines.append('  0 };')
        table.append(f'  {{ "{name}", a{i}, {len(data)} }},')
    lines.append('')
    lines.append('const Asset g_assets[] = {')
    lines.extend(table)
    lines.append('  { 0, 0, 0 },')
    lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
