/* Host-side tests for HID pointer report parsing: make test */
#include <stdio.h>
#include <string.h>
#include "input/hid.h"

static int failures;

#define CHECK(cond, ...) do { \
    if (!(cond)) { failures++; printf("FAIL %s:%d: ", __FILE__, __LINE__); printf(__VA_ARGS__); printf("\n"); } \
} while (0)

/* QEMU usb-tablet (hw/usb/dev-hid.c) */
static const unsigned char tablet[] = {
    0x05,0x01, 0x09,0x02, 0xa1,0x01, 0x09,0x01, 0xa1,0x00, 0x05,0x09, 0x19,0x01, 0x29,0x03,
    0x15,0x00, 0x25,0x01, 0x95,0x03, 0x75,0x01, 0x81,0x02, 0x95,0x01, 0x75,0x05, 0x81,0x01,
    0x05,0x01, 0x09,0x30, 0x09,0x31, 0x15,0x00, 0x26,0xff,0x7f, 0x35,0x00, 0x46,0xff,0x7f,
    0x75,0x10, 0x95,0x02, 0x81,0x02, 0x05,0x01, 0x09,0x38, 0x15,0x81, 0x25,0x7f, 0x35,0x00,
    0x45,0x00, 0x75,0x08, 0x95,0x01, 0x81,0x06, 0xc0, 0xc0,
};

/* Consumer-control report 1 first, then a 5-button relative mouse as report 2 */
static const unsigned char gaming[] = {
    0x05,0x0c, 0x09,0x01, 0xa1,0x01, 0x85,0x01, 0x19,0x00, 0x2a,0x3c,0x02, 0x15,0x00,
    0x26,0x3c,0x02, 0x95,0x01, 0x75,0x10, 0x81,0x00, 0xc0,
    0x05,0x01, 0x09,0x02, 0xa1,0x01, 0x85,0x02, 0x09,0x01, 0xa1,0x00, 0x05,0x09, 0x19,0x01,
    0x29,0x05, 0x15,0x00, 0x25,0x01, 0x95,0x05, 0x75,0x01, 0x81,0x02, 0x95,0x01, 0x75,0x03,
    0x81,0x01, 0x05,0x01, 0x09,0x30, 0x09,0x31, 0x16,0x01,0x80, 0x26,0xff,0x7f, 0x75,0x10,
    0x95,0x02, 0x81,0x06, 0x09,0x38, 0x15,0x81, 0x25,0x7f, 0x75,0x08, 0x95,0x01, 0x81,0x06,
    0xc0, 0xc0,
};

/* Boot keyboard: no pointer */
static const unsigned char keyboard[] = {
    0x05,0x01, 0x09,0x06, 0xa1,0x01, 0x05,0x07, 0x19,0xe0, 0x29,0xe7, 0x15,0x00, 0x25,0x01,
    0x75,0x01, 0x95,0x08, 0x81,0x02, 0x95,0x01, 0x75,0x08, 0x81,0x01, 0x95,0x06, 0x75,0x08,
    0x15,0x00, 0x25,0x65, 0x05,0x07, 0x19,0x00, 0x29,0x65, 0x81,0x00, 0xc0,
};

int main(void)
{
    HidLayout l;
    HidReport r;

    CHECK(hid_parse(tablet, sizeof(tablet), &l), "tablet parses");
    CHECK(l.absolute && l.report_id == 0, "tablet absolute, no report id");
    CHECK(l.x.off == 8 && l.x.size == 16 && l.x.lmax == 0x7fff && !l.x.sign, "tablet X field");
    CHECK(l.y.off == 24 && l.wheel.off == 40 && l.wheel.sign, "tablet Y/wheel fields");
    unsigned char t1[] = { 0x01, 0xff, 0x3f, 0x00, 0x10, 0xff };
    CHECK(hid_decode(&l, t1, sizeof(t1), &r) && r.x == 0x3fff && r.y == 0x1000 && r.buttons == 1 && r.wheel == -1,
          "tablet decode x=%d y=%d b=%u w=%d", r.x, r.y, r.buttons, r.wheel);
    CHECK(!hid_decode(&l, t1, 3, &r), "short report rejected");

    CHECK(hid_parse(gaming, sizeof(gaming), &l), "gaming mouse parses");
    CHECK(!l.absolute && l.report_id == 2, "relative, report id 2 (got %d)", l.report_id);
    CHECK(l.x.off == 8 && l.x.size == 16 && l.x.sign, "16-bit signed X after 8 bits of buttons");
    unsigned char g1[] = { 0x02, 0x02, 0xfb, 0xff, 0x07, 0x00, 0x01 };
    CHECK(hid_decode(&l, g1, sizeof(g1), &r) && r.x == -5 && r.y == 7 && r.buttons == 2 && r.wheel == 1,
          "gaming decode x=%d y=%d b=%u w=%d", r.x, r.y, r.buttons, r.wheel);
    unsigned char g2[] = { 0x01, 0xe9, 0x00 };
    CHECK(!hid_decode(&l, g2, sizeof(g2), &r), "consumer report ignored");

    CHECK(!hid_parse(keyboard, sizeof(keyboard), &l), "keyboard is not a pointer");
    CHECK(!hid_parse(tablet, 20, &l), "truncated descriptor without X/Y fails cleanly");

    hid_boot_mouse(&l);
    unsigned char b1[] = { 0x05, 0xfe, 0x03 };
    CHECK(hid_decode(&l, b1, sizeof(b1), &r) && r.x == -2 && r.y == 3 && r.buttons == 5, "boot mouse decode");

    if (failures) {
        printf("%d check(s) failed\n", failures);
        return 1;
    }
    printf("hid tests passed\n");
    return 0;
}
